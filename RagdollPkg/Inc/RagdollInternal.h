// Shared level geometry world: ONE Box3D world per level that holds the level
// BSP baked into a static triangle mesh plus every ragdoll's bodies/joints.
// Built lazily on the first ragdoll spawn and torn down when the last corpse
// disappears. Because the world origin coincides with the level origin (UU
// mapped by RAGDOLL_U2M), BSP vertices drop straight into Box3D coordinates.
// One mover brush (door / lift / train) mirrored as a KINEMATIC Box3D body:
// one thin convex slab per brush face (so non-convex movers keep their
// interior; Box3D mesh shapes only collide on static bodies), driven to the
// mover's Location/Rotation every world step (RagdollSyncMovers). See
// docs/plans/environment.md.
struct FRagdollMoverBody
{
	class AMover* Mover;
	b3BodyId      Body;
	FVector       LastLoc;        // pose the body was last driven to (UU)
	FRotator      LastRot;
	FLOAT         LastMoveTime;   // appSeconds() of the last pose change (crush checks look at recent movers)
	FVector       Vel;            // engine pose velocity (UU/s) from the last two poses; the kinematic target leads by it
	INT           NumSlabs;
	UBOOL         bEnabled;
	// Face planes in the mover's rigid frame (UU, outward normals) and
	// whether the brush is convex (every vertex behind every plane): the
	// exact inside test for lifts / doors; non-convex movers only get the
	// slab shell test.
	FPlane        LocalPlanes[64];   // plain array: UT's TArray::AddItem assigns into unconstructed memory
	INT           NumPlanes;
	UBOOL         bConvex;
};

struct FRagdollLevelWorld
{
	ULevel*     Level;          // ULevel whose BSP this world was built from
	b3WorldId   World;          // Box3D world handle (shared by all corpses)
	b3BodyId    Geometry;       // static body holding the level triangle mesh
	b3MeshData* Mesh;           // owned mesh data; must outlive the world
	FLOAT       MinZ;           // lowest solid BSP vertex Z (UU), for despawn
	FLOAT       LastStepTime;   // last appSeconds() stamp we stepped (dedupe)
	FLOAT       LastTickTime;   // Level->TimeSeconds of that step: the world steps ONCE per engine tick
	UBOOL       bBuilt;
	TArray<FRagdollMoverBody> Movers;   // kinematic mover bodies (empty when bMoverCollision is off)
};

