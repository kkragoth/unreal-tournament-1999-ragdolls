// Real-mesh mode per-vertex smooth skin data (one entry per mesh vertex). Each
// entry holds up to 3 bones with normalized weights summing to 1 (weight[0]
// dominant, lower weights may be 0); Off is the bind-space offset (UU,
// DrawScale=1) from the bone center, scaled by DrawScale in GetFrame.
struct FRagdollVertexBind
{
	INT    Bone[3];
	FVector Off[3];
	FLOAT  Weight[3];
};

// A planar cut through the skin (bind space, UU, DrawScale=1): point A,
// unit normal N (toward the child / the fragment's positive side). W is how
// far the original heat-weight seam ring wandered off the plane, R the ring's
// radius about the axis; both bound which parent-side vertices get moved onto
// the child side so a limb plane never claims skin on the far side of the body.
struct FRagdollCutPlane
{
	FVector A;
	FVector N;
	FLOAT   W;
	FLOAT   R;
	UBOOL   bValid;
	FRagdollCutPlane() : A( 0, 0, 0 ), N( 0, 0, 1 ), W( 0 ), R( 0 ), bValid( 0 ) {}
};

// Authored cut site of one bone (RagdollCutSites.h, generated by
// tools/gore_cuts.py from the datasets; docs/plans/gore-variation.md). The cut
// plane runs A(t) = A + t (E - A) with normal E - A, for t in [TMin, TMax]
// where the offline sweep found the seam clips cleanly (no fused faces, one
// rim loop per side). Band / Radius are the FRagdollCutPlane W / R the
// classifier uses. TMin < 0: no clean site (fall back to the heat-seam fit).
struct FRagdollCutSite
{
	FVector A;
	FVector E;
	FLOAT   TMin, TMax;
	FLOAT   Band;
	FLOAT   Radius;
	FLOAT   RimR;
};

struct FRagdollCutSiteTable
{
	const TCHAR*    DatasetName;
	FRagdollCutSite Sites[RAGDOLL_BONE_COUNT];
};

// One collision hull of a skeleton body, in bind space relative to the body
// origin (UU, DrawScale=1): the dataset box (index 0, possibly trimmed at the
// socket) and the overhang hulls (feet, hands, skull). Tracked so a mid-bone
// cut can clip the hull to the severed part (RagdollTrimHullsForCut).
#define RAGDOLL_MAX_HULLS 6
struct FRagdollHull
{
	b3ShapeId Shape;
	FVector   C;        // centre offset from the body origin
	FVector   H;        // half extents
	FLOAT     Density;  // kg/m^3 the shape was created with
};

// Runtime state for one ragdolling carcass. Stored in a process-global map
// keyed by the owning actor so URagdollMesh::GetFrame can reach it.
struct FRagdollState
{
	UBOOL         bBuilt;
	UBOOL         bFrameLogged;
	UBOOL         bFrameRangeLogged;
	UBOOL         bOutOfWorldLogged;
	UBOOL         bContactLog;   // one of the first corpses: log the contact census
	INT   SyncCount;
	INT   NumBodies;  // bodies actually created (12 real-mesh, 14 box)
	b3WorldId     World;   // shared level world (see FRagdollLevelWorld)
	URagdollMesh* Mesh;
	// Owning carcass; also stored as b3BodyDef.userData on every body of this
	// corpse (skeleton and fragments) so a contact's other body can be told
	// apart as level geometry (NULL), this corpse, or another corpse.
	class ARagdollCarcass* Owner;
	b3BodyId      Bodies[RAGDOLL_BONE_COUNT];
	b3Vec3        RestPositions[RAGDOLL_BONE_COUNT];
	b3Quat        RestRotations[RAGDOLL_BONE_COUNT];
	const FRagdollBoneDef* BoneDefs;  // active skeleton (dataset or canonical)

	// Death pose captured from the dying pawn (set by SetDeathPose before
	// BuildRagdoll): the corpse spawns facing the pawn's yaw with its arms
	// raised toward the aim pitch instead of frozen in the arms-down bind pose.
	INT   SpawnYaw;      // dead pawn facing (Unreal units)
	INT   SpawnPitch;    // dead pawn aim pitch (Unreal units)
	UBOOL bHasDeathPose;

	// Per-vertex smooth skin data (indexed by mesh vertex); empty in box mode.
	TArray<FRagdollVertexBind> VertBinds;

	// Gore state. Joints[child] is the Box3D joint attaching body 'child' to
	// its parent (GRagdollBoneParent); Cut[child] once that joint is destroyed
	// (dismemberment/gib), Alive[body] false once the body itself is removed
	// (decapitation hands the head to the stock UTHeads chunk). BindPos holds
	// the bind-space position (UU, DrawScale=1) of every mesh vertex, grown as
	// seam vertices are duplicated; CapMaterial indexes the dark wound material
	// used by the stump caps (-1 = none, caps use material 0).
	b3JointId Joints[RAGDOLL_BONE_COUNT];
	EJointKind JointKind[RAGDOLL_BONE_COUNT];   // kind of Joints[child] (census labels)
	UBOOL     Alive[RAGDOLL_BONE_COUNT];
	UBOOL     Cut[RAGDOLL_BONE_COUNT];
	const struct FRagdollDatasetEntry* Dataset;
	TArray<FVector> BindPos;
	INT       CapMaterial;
	INT       NumSplits;      // how many times the mesh has been re-split (diagnostics)

	// Fragment bodies (see RAGDOLL_MAX_EXTRA). ExtraCenter is the fragment's
	// bind-space centre (UU, DrawScale=1), ExtraRadius its bounding radius.
	// Per-corpse copies of the skin textures that wounds are painted into
	// (one per MultiSkins slot, made lazily on the first wound in that slot).
	UTexture* WoundSkins[8];

	INT       NumExtra;
	b3BodyId  ExtraBodies[RAGDOLL_MAX_EXTRA];
	FVector   ExtraCenter[RAGDOLL_MAX_EXTRA];
	FLOAT     ExtraRadius[RAGDOLL_MAX_EXTRA];

	// Cut planes (RagdollGore.cpp). JointPlanes[child] is fitted once, when
	// that joint is first seen cut, from the heat-weight seam ring; FragPlanes
	// are the random planes RagdollFragmentBody split bodies with, in
	// creation order. Seam faces are clipped against whichever plane separates
	// their two islands, so the stump rims are exact planar polygons.
	FRagdollCutPlane JointPlanes[RAGDOLL_BONE_COUNT];
	INT              NumFragPlanes;
	FRagdollCutPlane FragPlanes[RAGDOLL_MAX_EXTRA];
	// Config flag bPlanarCuts (read at build time): planar clipping ON, or the
	// 2026-10-10 morning behaviour (dominant-bone islands, duplicated skirts,
	// centroid fans). OFF by default: the planar version looked broken in the
	// user's playtest (see docs/handoff-2026-10-10-gore.md).
	UBOOL            bPlanarCuts;
	// Config flag bFragmentBodies (read at build time): a blast may also
	// shatter the torn-off head / torso / pelvis / thighs into random-plane
	// chunks (RagdollFragmentBody). OFF by default since 2026-10-10: the user
	// saw "the torso collapsing into several pieces with ugly fan-outs" even
	// with planar cuts off - those pieces were these fragments.
	UBOOL            bFragmentBodies;

	// Cut variation (docs/plans/gore-variation.md). HitT[b]: where body b was
	// last hit, as the parameter t along its cut-site axis (bind space; -1 =
	// unknown), recorded by RagdollHit / RagdollBlast. CutT[b]: the t the cut
	// of joint b was made at (-1 = heat-seam fit, no site). StubOnParent[b]:
	// the broken bone shaft protrudes from the stump (else from the limb);
	// StubLen[b]: its length (UU). Knobs read at build: CutVariation (0 =
	// always TMin, like the old joint cuts), BoneStubChance, BoneStubLength,
	// bModelledCaps (false = the old centroid fans).
	FLOAT            HitT[RAGDOLL_BONE_COUNT];
	FLOAT            CutT[RAGDOLL_BONE_COUNT];
	UBOOL            StubOnParent[RAGDOLL_BONE_COUNT];
	FLOAT            StubLen[RAGDOLL_BONE_COUNT];
	FLOAT            CutVariation;
	UBOOL            bBoneStubs;      // false = socket caps on both sides, no bone geometry
	FLOAT            BoneStubChance;
	FLOAT            BoneStubLength;
	UBOOL            bModelledCaps;
	FLOAT            DrawScale;       // the actor's DrawScale at build (hull maths)
	INT              NumOrigVerts;    // dataset vertex count; later vertices are clip points / caps

	// Sustained push (RagdollPush: the pulse beam). The beam deals its damage
	// in packets every 0.22 s; an impulse per packet only twitched the body
	// (friction ate a 0.2 m/s kick within a frame), so a packet is turned
	// into a force on the hit body (at PushLocal, body space) applied every
	// step until PushUntil (level time), jointed neighbours taking a third per
	// kilogram at their centres. PushBody -1 = none.
	INT              PushBody;
	b3Vec3           PushDir;         // unit, world
	FLOAT            PushForce;       // N on the hit body
	b3Vec3           PushLocal;       // application point, body space (m)
	FLOAT            PushUntil;

	// Collision hulls per skeleton body (see FRagdollHull).
	INT              NumHulls[RAGDOLL_BONE_COUNT];
	FRagdollHull     Hulls[RAGDOLL_BONE_COUNT][RAGDOLL_MAX_HULLS];

	// Per-body damage ledger (2026-10-11 damage model): HitDamage adds the
	// shot's cutting damage to the ONE body under the ray, BlastDamage adds
	// the blast's falloff-weighted damage to every body in range. A body
	// whose ledger reaches GRagdollSeverThreshold (x DismemberScale) is
	// reported to script in the sever mask; script tears it off.
	FLOAT            PartDamage[RAGDOLL_BONE_COUNT];
	// Gravity scale of this corpse's bodies (zone gravity / UT default x the
	// GravityScale knob); fragment bodies created later copy it.
	FLOAT            GravityScale;

	// Environment (docs/plans/environment.md). Per body: the zone its centre
	// was in at the last step, the submerged fraction applied (0..1) and the
	// gravity scale applied, so the per-step pass only touches Box3D when
	// something changed. Knobs read at build (globalconfig floats).
	class AZoneInfo* BodyZone[RAGDOLL_MAX_BONES];
	FLOAT            BodyWet[RAGDOLL_MAX_BONES];
	FLOAT            BodyGrav[RAGDOLL_MAX_BONES];
	FLOAT            WaterBuoyancy;   // buoyant force / weight when fully submerged (1.08 = floats slowly)
	FLOAT            WaterDrag;       // linear + angular damping (1/s) and current coupling when submerged
	FLOAT            AirDrag;         // coupling (1/s) toward a non-water zone's ZoneVelocity (wind)
	FLOAT            ZoneWindScale;   // 0 = ignore ZoneVelocity outside water
	FLOAT            AngDamp;         // the AngularDamping knob (restored when a body leaves water)
	UBOOL            bCrushed;        // a main-island body was inside a mover brush: corpse is despawning
	BYTE             CrushHits[RAGDOLL_MAX_BONES];   // consecutive inside-a-mover checks per body (debounce)
	UBOOL            bDoomed;         // despawning (destructive zone / crushed); skip further checks
	INT              ZoneLogCount;

	FRagdollState()
	: bBuilt( 0 ), bFrameLogged( 0 ), bFrameRangeLogged( 0 ), bOutOfWorldLogged( 0 ), bContactLog( 0 )
	, SyncCount( 0 ), NumBodies( 0 ), World( b3_nullWorldId ), Mesh( NULL ), Owner( NULL ), BoneDefs( NULL )
	, SpawnYaw( 0 ), SpawnPitch( 0 ), bHasDeathPose( 0 )
	, Dataset( NULL ), CapMaterial( -1 ), NumSplits( 0 ), NumExtra( 0 ), NumFragPlanes( 0 ), bPlanarCuts( 0 ), bFragmentBodies( 0 )
	, CutVariation( 1.0f ), bBoneStubs( 0 ), BoneStubChance( 1.0f ), BoneStubLength( 1.0f ), bModelledCaps( 1 ), DrawScale( 1.0f ), NumOrigVerts( 0 )
	, PushBody( -1 ), PushDir( b3Vec3_zero ), PushForce( 0.0f ), PushLocal( b3Vec3_zero ), PushUntil( 0.0f )
	, GravityScale( 1.0f )
	, WaterBuoyancy( 1.08f ), WaterDrag( 2.0f ), AirDrag( 0.5f ), ZoneWindScale( 1.0f ), AngDamp( 0.4f )
	, bCrushed( 0 ), bDoomed( 0 ), ZoneLogCount( 0 )
	{
		for( INT p=0; p<RAGDOLL_BONE_COUNT; p++ )
		{
			PartDamage[p]   = 0.0f;
			HitT[p]         = -1.0f;
			CutT[p]         = -1.0f;
			StubOnParent[p] = 1;
			StubLen[p]      = 0.0f;
			NumHulls[p]     = 0;
		}
		for( INT z=0; z<RAGDOLL_MAX_BONES; z++ )
		{
			BodyZone[z]  = NULL;
			BodyWet[z]   = 0.0f;
			BodyGrav[z]  = 1.0f;
			CrushHits[z] = 0;
		}
		for( INT t=0; t<8; t++ )
			WoundSkins[t] = NULL;
		for( INT e=0; e<RAGDOLL_MAX_EXTRA; e++ )
		{
			ExtraBodies[e] = b3_nullBodyId;
			ExtraCenter[e] = FVector( 0, 0, 0 );
			ExtraRadius[e] = 0.0f;
		}
		for( INT i=0; i<RAGDOLL_BONE_COUNT; i++ )
		{
			Bodies[i]        = b3_nullBodyId;
			RestPositions[i] = b3Vec3_zero;
			RestRotations[i] = b3Quat_identity;
			Joints[i]        = b3_nullJointId;
			JointKind[i]     = JK_Ball;
			Alive[i]         = 0;
			Cut[i]           = 0;
		}
	}
};

