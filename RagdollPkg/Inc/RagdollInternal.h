// Canonical bone layout (Unreal units, Z up). Half extents and center offsets
// are relative to the pelvis origin and are scaled by the actor DrawScale.
struct FRagdollBoneDef
{
	float HX, HY, HZ;    // half extents
	float CX, CY, CZ;    // center offset from pelvis
	float MassKg;        // approximate mass in kilograms
};

#define RAGDOLL_BONE_COUNT 14

// Joint specification (BuildRagdollImpl / AddJoint). Ball joints: L0 = cone
// half-angle, L1/L2 = twist range; hinges: L0/L1 = flexion range; radians.
// Friction is the zero-speed motor torque in Nm (scaled by JointFrictionScale).
// AX/AY/AZ (ball joints only): direction the swing cone is centred on, in
// bind space (left = -X, front = +Y, up = +Z), as the direction the child
// limb would point at the cone's centre. Zero = the bind direction (cone
// centred on the hanging limb). Box3D clamps every cone to 90 deg, so a
// bind-centred shoulder could never lift the arm above horizontal; aiming
// the cone out-and-forward gives the arm the whole front/outer hemisphere.
// JK_Pivot (hips): a hinge with a cone of play. The joint frames' z axis is
// the hinge axis AX/AY/AZ (bind space; +X = the lateral axis, positive =
// the hanging limb swings forward), so Box3D's TWIST limit carries the
// asymmetric flexion range L1..L2 (hip: -20..+110 deg) and its CONE limit
// L0 bounds the combined abduction + long-axis rotation (the "play", ~30
// deg). An isotropic cone cannot express a hip (flexion 110, abduction
// 40): every corpse ended up in the splits at the 50-69 deg cone. Rest is
// the spring's rest flexion.
enum EJointKind
{
	JK_Ball,
	JK_Hinge,
	JK_Pivot
};

struct FRagdollJointSpec
{
	EJointKind Kind;
	FLOAT L0, L1, L2;
	FLOAT Friction;
	FLOAT AX, AY, AZ;
	FLOAT Rest;
};

// Per-model joint table (RagdollJointTuning.h, generated by
// tools/build_joint_tuning.py from tools/rigs/<Sel>.tuning.json). Covers the
// 11 real-mesh joints in AddJoint order (spine, neck, head, upper arm L/R,
// forearm L/R, thigh L/R, shin L/R); the ankles only exist on box mannequins
// and keep the global table. AnchorOffsets move the dataset anchors (UU).
#define RAGDOLL_TUNED_JOINTS 11
struct FRagdollJointTuning
{
	const TCHAR*      DatasetName;
	FRagdollJointSpec Joints[RAGDOLL_TUNED_JOINTS];
	FVector           AnchorOffsets[RAGDOLL_TUNED_JOINTS];
};

